"""Export a trained balance policy to plain C (and JSON), with test vectors.

    .venv/bin/python model/mj/export_policy.py [model/mj/runs/best_deployable.pt] [--out model/deploy]

Writes to --out:
  policy.pt              a copy of the exported checkpoint
  bizbot_policy.h / .c   the network and a runtime that builds its observation exactly as
                         sim/bizbot_mj/env.py does (history, wheel-rotation integral, rate limit)
  bizbot_policy.json     the same weights and constants, for any other port
  test_vectors.h         sensor sequences recorded in the sim with the commands the policy sent
  test_policy.c          host test: checks the C runtime reproduces those commands
  SPEC.md                the input and output contract, in plain words
Then compiles and runs the host test with the system C compiler.
"""

import argparse
import json
import shutil
import subprocess
import sys
from dataclasses import replace
from pathlib import Path

import numpy as np
import torch

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "sim"))
sys.path.insert(0, str(HERE))


def c_array(name, a, per_line=8):
    flat = np.asarray(a, dtype=np.float32).ravel()

    def lit(v):
        s = f"{v:.9g}"
        return (s if any(c in s for c in ".e") else s + ".0") + "f"   # 27 -> 27.0f, a valid C float

    body = ",\n".join("    " + ", ".join(lit(v) for v in flat[i:i + per_line])
                      for i in range(0, flat.size, per_line))
    return f"static const float {name}[{flat.size}] = {{\n{body}\n}};\n"


def record_vectors(policy, env_kw, n_robots=4, ticks=400):
    """Sensor inputs per tick and the command the sim sent, for robots that stay up."""
    from bizbot_mj import Randomization, U
    from bizbot_mj.env import BalanceEnv, EnvConfig
    rand = replace(Randomization(), push_rate=U(0, 0, 0), change_rate=U(0, 0, 0))
    out = []
    seed = 100
    while len(out) < n_robots:
        scale = 0.0 if not out else 0.5
        env = BalanceEnv(EnvConfig(n_envs=1, episode_s=1e9, **env_kw), rand, seed=seed, scale=scale)
        seed += 1
        pl = env.plant
        sense = lambda: [float(pl.imu_pitch[0]), float(pl.imu_accel[0]),
                         float(0.5 * (pl.fb_rpm[0, 0] + pl.fb_rpm[1, 0])), float(pl.batt_meas[0])]
        obs = env._obs()
        S, Uc, A = [sense()], [], []
        fell = False
        for k in range(ticks):
            a = policy(obs)
            A.append(float(a[0]))
            obs, _, term, _, _ = env.step(a)
            Uc.append(float(env.u[0]))
            if term[0]:
                fell = True
                break
            if k < ticks - 1:
                S.append(sense())
        if not fell:
            out.append({"sensors": S, "u": Uc, "action": A})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("policy", nargs="?", type=Path, default=HERE / "runs" / "best_deployable.pt")
    ap.add_argument("--out", type=Path, default=HERE.parent / "deploy")
    args = ap.parse_args()
    from ppo import load_policy
    ck = torch.load(args.policy, weights_only=False)
    assert ck.get("kind") == "td3" and not ck["td3"].get("actor_priv"), "needs a sensor-only TD3 actor"
    assert ck["td3"]["activation"] == "elu"
    sd = {k: v.numpy().astype(np.float64) for k, v in ck["actor"].items()}
    W1, b1, W2, b2, W3, b3 = (sd["net.0.weight"], sd["net.0.bias"], sd["net.2.weight"], sd["net.2.bias"],
                              sd["net.4.weight"], sd["net.4.bias"])
    mean = np.array(ck["obs_norm"]["mean"])
    std = np.sqrt(np.array(ck["obs_norm"]["var"]) + 1e-8)
    env = ck["env"]
    H, OBS, HID = env["history"], W1.shape[1], W1.shape[0]
    assert OBS == 4 * H + 2 and W2.shape == (HID, HID) and W3.shape == (1, HID)
    C = dict(history=H, obs=OBS, hidden=HID, dt=env["policy_dt"], max_cmd=env["max_cmd"],
             rate_limit=env["action_rate_limit"], leak_s=env["integral_leak_s"],
             integral_limit=env["integral_limit"], g=9.81, norm_clip=10.0)
    out = args.out
    out.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(args.policy, out / "policy.pt")

    # --- JSON ---------------------------------------------------------------------
    (out / "bizbot_policy.json").write_text(json.dumps({
        "source": str(args.policy), "constants": C,
        "obs_mean": mean.tolist(), "obs_std": std.tolist(),
        "W1": W1.tolist(), "b1": b1.tolist(), "W2": W2.tolist(), "b2": b2.tolist(),
        "W3": W3.tolist(), "b3": b3.tolist()}))

    # --- C header and source ----------------------------------------------------------
    (out / "bizbot_policy.h").write_text(f"""// Generated by model/mj/export_policy.py from {args.policy.name}. Do not edit by hand.
// See SPEC.md for the input and output contract.
#pragma once
#include <stdint.h>

#define BIZBOT_POLICY_HISTORY {H}
#define BIZBOT_POLICY_OBS {OBS}
#define BIZBOT_POLICY_HIDDEN {HID}
#define BIZBOT_POLICY_PERIOD_MS {int(round(C['dt'] * 1000))}

typedef struct {{
    float hist[BIZBOT_POLICY_HISTORY][4];  // oldest first: pitch/10, accel/g, rpm/60, command
    float u;                               // last command sent, normalised [-1, 1]
    float integral;                        // leaky wheel rotation, revolutions
    int fresh;                             // 1 until the first tick after a reset
}} BizbotPolicyState;

#ifdef __cplusplus
extern "C" {{
#endif

// Call when balancing (re)starts; the next tick fills the history with its readings.
void bizbot_policy_reset(BizbotPolicyState* s);

// Call every BIZBOT_POLICY_PERIOD_MS with the latest readings:
//   pitch_deg       IMU pitch, degrees, positive = leaning forward
//   accel_fwd_mps2  raw accelerometer along the robot's forward axis, m/s^2, gravity included
//                   (reads about -9.81*sin(pitch) at rest)
//   wheel_rpm       mean of left and right wheel rpm, positive = rolling forward
//   battery_v       battery voltage, volts
// Returns the hoverboard speed command, -{C['max_cmd']}..{C['max_cmd']}, positive = drive forward.
int16_t bizbot_policy_tick(BizbotPolicyState* s, float pitch_deg, float accel_fwd_mps2,
                           float wheel_rpm, float battery_v);

// The bare network: normalised-input pipeline included, obs -> action in [-1, 1].
float bizbot_policy_forward(const float obs[BIZBOT_POLICY_OBS]);

#ifdef __cplusplus
}}
#endif
""")
    src = [f"// Generated by model/mj/export_policy.py from {args.policy.name}. Do not edit by hand.\n",
           '#include "bizbot_policy.h"\n#include <math.h>\n#include <string.h>\n\n',
           c_array("OBS_MEAN", mean), c_array("OBS_INV_STD", 1.0 / std),
           c_array("W1", W1), c_array("B1", b1), c_array("W2", W2), c_array("B2", b2),
           c_array("W3", W3), c_array("B3", b3),
           f"""
static float elu(float x) {{ return x > 0.0f ? x : expm1f(x); }}

float bizbot_policy_forward(const float obs[BIZBOT_POLICY_OBS]) {{
    float x[BIZBOT_POLICY_OBS], h1[BIZBOT_POLICY_HIDDEN], h2[BIZBOT_POLICY_HIDDEN];
    for (int i = 0; i < BIZBOT_POLICY_OBS; ++i) {{
        float v = (obs[i] - OBS_MEAN[i]) * OBS_INV_STD[i];
        x[i] = v > {C['norm_clip']}f ? {C['norm_clip']}f : (v < -{C['norm_clip']}f ? -{C['norm_clip']}f : v);
    }}
    for (int j = 0; j < BIZBOT_POLICY_HIDDEN; ++j) {{
        const float* w = &W1[j * BIZBOT_POLICY_OBS];
        float acc = B1[j];
        for (int i = 0; i < BIZBOT_POLICY_OBS; ++i) acc += w[i] * x[i];
        h1[j] = elu(acc);
    }}
    for (int j = 0; j < BIZBOT_POLICY_HIDDEN; ++j) {{
        const float* w = &W2[j * BIZBOT_POLICY_HIDDEN];
        float acc = B2[j];
        for (int i = 0; i < BIZBOT_POLICY_HIDDEN; ++i) acc += w[i] * h1[i];
        h2[j] = elu(acc);
    }}
    float acc = B3[0];
    for (int i = 0; i < BIZBOT_POLICY_HIDDEN; ++i) acc += W3[i] * h2[i];
    float a = tanhf(acc);
    return a > 1.0f ? 1.0f : (a < -1.0f ? -1.0f : a);
}}

void bizbot_policy_reset(BizbotPolicyState* s) {{
    memset(s, 0, sizeof(*s));
    s->fresh = 1;
}}

int16_t bizbot_policy_tick(BizbotPolicyState* s, float pitch_deg, float accel_fwd_mps2,
                           float wheel_rpm, float battery_v) {{
    const float frame[4] = {{pitch_deg / 10.0f, accel_fwd_mps2 / {C['g']}f, wheel_rpm / 60.0f, 0.0f}};
    if (s->fresh) {{
        // As the sim's reset: the whole history is the first reading, command 0, integral 0.
        for (int k = 0; k < BIZBOT_POLICY_HISTORY; ++k) {{
            memcpy(s->hist[k], frame, sizeof(frame));
        }}
        s->u = 0.0f;
        s->integral = 0.0f;
        s->fresh = 0;
    }} else {{
        // As the sim's step: leaky integral of wheel rotation, then shift in the new frame
        // paired with the command that was applied while it was measured.
        const float decay = {np.exp(-C['dt'] / C['leak_s']):.9g}f;
        float integ = s->integral * decay - wheel_rpm / 60.0f * {C['dt']}f;
        s->integral = integ > {C['integral_limit']}f ? {C['integral_limit']}f
                    : (integ < -{C['integral_limit']}f ? -{C['integral_limit']}f : integ);
        memmove(s->hist[0], s->hist[1], sizeof(s->hist) - sizeof(s->hist[0]));
        memcpy(s->hist[BIZBOT_POLICY_HISTORY - 1], frame, sizeof(frame));
        s->hist[BIZBOT_POLICY_HISTORY - 1][3] = s->u;
    }}
    float obs[BIZBOT_POLICY_OBS];
    memcpy(obs, s->hist, sizeof(s->hist));
    obs[BIZBOT_POLICY_OBS - 2] = (battery_v - 37.0f) / 5.0f;
    obs[BIZBOT_POLICY_OBS - 1] = s->integral / {C['integral_limit']}f;
    const float a = bizbot_policy_forward(obs);
    float du = a - s->u;
    du = du > {C['rate_limit']}f ? {C['rate_limit']}f : (du < -{C['rate_limit']}f ? -{C['rate_limit']}f : du);
    s->u += du;
    return (int16_t)(s->u * {C['max_cmd']}.0f);  // truncates toward zero, as the sim
}}
"""]
    (out / "bizbot_policy.c").write_text("".join(src))

    # --- test vectors from the sim ----------------------------------------------------
    policy, _ = load_policy(args.policy)
    env_kw = {k: v for k, v in env.items() if k not in ("n_envs", "episode_s")}
    vecs = record_vectors(policy, env_kw)
    th = ["// Generated by model/mj/export_policy.py: sim sensor sequences and the commands sent.\n#pragma once\n"]
    th.append(f"#define TV_ROBOTS {len(vecs)}\n#define TV_TICKS {len(vecs[0]['u'])}\n")
    for r, v in enumerate(vecs):
        th.append(c_array(f"TV_SENSORS_{r}", v["sensors"]))
        th.append(c_array(f"TV_U_{r}", v["u"]))
    th.append("static const float* TV_SENSORS[TV_ROBOTS] = {" + ", ".join(f"TV_SENSORS_{r}" for r in range(len(vecs))) + "};\n")
    th.append("static const float* TV_U[TV_ROBOTS] = {" + ", ".join(f"TV_U_{r}" for r in range(len(vecs))) + "};\n")
    (out / "test_vectors.h").write_text("".join(th))
    (out / "test_policy.c").write_text(f"""// Host test: the C runtime must reproduce the commands the sim sent.
#include <stdio.h>
#include <stdlib.h>
#include <math.h>
#include "bizbot_policy.h"
#include "test_vectors.h"

int main(void) {{
    double worst_u = 0.0;
    int cmd_mismatch = 0, total = 0;
    for (int r = 0; r < TV_ROBOTS; ++r) {{
        BizbotPolicyState s;
        bizbot_policy_reset(&s);
        for (int k = 0; k < TV_TICKS; ++k) {{
            const float* x = &TV_SENSORS[r][k * 4];
            int16_t cmd = bizbot_policy_tick(&s, x[0], x[1], x[2], x[3]);
            double du = fabs((double)s.u - (double)TV_U[r][k]);
            if (du > worst_u) worst_u = du;
            int16_t want = (int16_t)(TV_U[r][k] * {C['max_cmd']}.0f);
            if (cmd != want && abs(cmd - want) > 1) ++cmd_mismatch;
            ++total;
        }}
    }}
    printf("ticks %d, worst |u_c - u_sim| = %.2e, commands off by more than 1 unit: %d\\n",
           total, worst_u, cmd_mismatch);
    return (worst_u < 1e-3 && cmd_mismatch == 0) ? 0 : 1;
}}
""")

    # --- spec ------------------------------------------------------------------------------
    macs = OBS * HID + HID * HID + HID
    (out / "SPEC.md").write_text(f"""# BizBot balance policy: contract

Source: `{args.policy}`. Network: {OBS} inputs -> {HID} ELU -> {HID} ELU -> 1 tanh,
{W1.size + W2.size + W3.size + b1.size + b2.size + b3.size} parameters, about {macs} multiply-adds per tick.

## Call pattern
- `bizbot_policy_reset(&s)` when balancing (re)starts.
- `bizbot_policy_tick(&s, pitch_deg, accel_fwd_mps2, wheel_rpm, battery_v)` every
  {int(round(C['dt'] * 1000))} ms with the latest readings; send the returned value to the hoverboard as the
  speed command (steer 0). It is already rate limited ({C['rate_limit']} of full scale per tick) and
  scaled to +-{C['max_cmd']} (truncated toward zero).

## Inputs (signs are what the sim used; check them on the robot)
| input | units | sign | note |
|---|---|---|---|
| pitch_deg | degrees | + leaning forward | the IMU reading; an offset up to about +-3 deg is fine |
| accel_fwd_mps2 | m/s^2 | + accelerating forward | raw accelerometer along the forward axis, gravity included: about -9.81*sin(pitch) at rest |
| wheel_rpm | rpm | + rolling forward | mean of left and right after their individual signs are fixed |
| battery_v | volts | | |

The runtime keeps the last {H} ticks of (pitch/10, accel/9.81, rpm/60, its own command),
a leaky sum of wheel revolutions (decays over {C['leak_s']:.0f} s, clipped to +-{C['integral_limit']}),
and appends (battery-37)/5 and that sum/{C['integral_limit']}; the network normalises each input with the
training statistics and clips to +-{C['norm_clip']}.

## Output
Hoverboard speed command, + = wheels drive the robot forward. The hoverboard must be in speed mode.

## Verified
`test_policy.c` replays {len(vecs)} simulated robots x {len(vecs[0]['u'])} ticks through the C runtime and
checks it reproduces the sim's commands.
""")

    # --- compile and run the host test ---------------------------------------------------
    exe = out / "test_policy"
    subprocess.run(["cc", "-O2", "-std=c99", "-o", str(exe), str(out / "test_policy.c"), str(out / "bizbot_policy.c"),
                    "-lm"], check=True)
    r = subprocess.run([str(exe)], capture_output=True, text=True)
    print(r.stdout.strip())
    print("host test:", "PASS" if r.returncode == 0 else "FAIL")
    print(f"wrote {out}: {macs} multiply-adds per tick")


if __name__ == "__main__":
    main()
